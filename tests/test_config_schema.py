@pytest.mark.unit
class TestTradingAgentsGraphIntegration:
    def _build_graph(self, tmp_path, monkeypatch, config):
        from unittest.mock import MagicMock

        from tradingagents.graph import trading_graph as tg

        monkeypatch.setattr(
            tg, "create_llm_client",
            lambda **kw: MagicMock(get_llm=lambda: MagicMock()),
        )
        monkeypatch.setattr(
            tg.GraphSetup, "setup_graph",
            lambda self, selected_analysts=None, **kw: MagicMock(),
        )
        return tg.TradingAgentsGraph(config=config)

    def test_graph_construction_does_not_raise_on_valid_config(self, tmp_path, monkeypatch):
        cfg = dict(DEFAULT_CONFIG)
        cfg["audit_dir"] = str(tmp_path)
        cfg["audit_full_trace_enabled"] = False
        cfg["checkpoint_enabled"] = False
        self._build_graph(tmp_path, monkeypatch, cfg)  # must not raise

    def test_graph_construction_warns_but_does_not_raise_on_bad_config_by_default(
        self, tmp_path, monkeypatch
    ):
        cfg = dict(DEFAULT_CONFIG)
        cfg["audit_dir"] = str(tmp_path)
        cfg["audit_full_trace_enabled"] = False
        cfg["checkpoint_enabled"] = False
        cfg["trade_filter_threshold"] = 5.0  # out of [0, 1] range
        self._build_graph(tmp_path, monkeypatch, cfg)  # must not raise

    def test_graph_construction_raises_on_bad_config_in_strict_mode(self, tmp_path, monkeypatch):
        cfg = dict(DEFAULT_CONFIG)
        cfg["audit_dir"] = str(tmp_path)
        cfg["audit_full_trace_enabled"] = False
        cfg["checkpoint_enabled"] = False
        cfg["trade_filter_threshold"] = 5.0
        cfg["strict_config"] = True
        with pytest.raises(ConfigValidationError):
            self._build_graph(tmp_path, monkeypatch, cfg)
